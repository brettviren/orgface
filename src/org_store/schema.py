"""The JSON Schema for the canonical model, generated and checked in.

:mod:`org_store.model` is the definition; this renders it to JSON Schema
so that consumers which are not Python -- the Emacs side, an MCP client,
anything reading the stored JSON directly -- have something to validate
against.

The rendered schema is committed to the tree and regenerated by::

    uv run python -m org_store.schema

A test asserts the committed copy still matches the model, so a change to
the model that alters the stored shape shows up as a schema diff to review
rather than as a silent change nobody noticed.
"""

from __future__ import annotations

import json
import sys
from pathlib import Path
from typing import Any

from .model import SCHEMA_VERSION, OrgDocument

SCHEMA_DIR = Path(__file__).parent / "schemas"
SCHEMA_FILE = SCHEMA_DIR / "org-document.schema.json"

SCHEMA_ID = (
    "https://brettviren.github.io/org-cli-helper/schema/"
    f"v{SCHEMA_VERSION}/org-document.schema.json"
)


def generate() -> dict[str, Any]:
    """Build the schema from the model.

    Validation mode on purpose: this is the contract for "is this a
    conforming org document", which has to accept what ``ox-json`` emits,
    not merely what :meth:`OrgDocument.dump` produces.
    """
    schema = OrgDocument.model_json_schema(
        by_alias=True, mode="validation", ref_template="#/$defs/{model}"
    )
    return {
        "$schema": "https://json-schema.org/draft/2020-12/schema",
        "$id": SCHEMA_ID,
        **schema,
    }


def rendered() -> str:
    """The schema as the committed file should contain it, byte for byte."""
    return json.dumps(generate(), indent=2, sort_keys=True) + "\n"


def write(path: Path | None = None) -> Path:
    """Write the schema to PATH, defaulting to the committed location."""
    target = SCHEMA_FILE if path is None else path
    target.parent.mkdir(parents=True, exist_ok=True)
    target.write_text(rendered(), encoding="utf-8")
    return target


def main() -> int:
    """Regenerate the committed schema, reporting whether it changed."""
    before = SCHEMA_FILE.read_text(encoding="utf-8") if SCHEMA_FILE.exists() else None
    after = rendered()
    SCHEMA_DIR.mkdir(parents=True, exist_ok=True)
    SCHEMA_FILE.write_text(after, encoding="utf-8")
    if before == after:
        print(f"unchanged: {SCHEMA_FILE}")
    else:
        print(f"updated: {SCHEMA_FILE}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
